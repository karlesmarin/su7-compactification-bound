def max_logbudget(Atgt, Ktgt):
    """max of U_total ln2 + V_total ln3 over  sum n_j v_j = (Atgt, Ktgt),  n >= 0 integer,
    with U_total = U_gauge + sum n_j U_j.  Exact and complete: every generator has A4 >= 0 and
    only 7(+,+) has A4 = 0, and with 8D pinned too its multiplicity is forced, so the feasible
    set is finite."""
    best = None
    idx = [j for j in range(8) if AV[j] > 0]

    def rec(i, a, k, u, v, n):
        nonlocal best
        if i == len(idx):
            # what is left must be made by 7(+,+): A4 must already match, 8D must be short by 6m
            if a != 0:
                return
            if k % 6:
                return
            m = k // 6                     # each 7(+,+) contributes 8D = -6, so we need k = -6m
            if m > 0:
                return
            m = -m
            uu = u + m * GQ_SYM[0][2] + U_OFF
            vv = v + V_OFF
            cand = uu * LN2 + vv * LN3
            if best is None or cand > best[0]:
                best = (cand, uu, vv, tuple(n) + (m,), sum(n) + m)
            return
        j = idx[i]
        lim = a // AV[j]
        for c in range(lim + 1):
            n.append(c)
            rec(i + 1, a - c * AV[j], k - c * KV[j], u + c * GQ_SYM[j][2],
                v + c * GQ_SYM[j][1], n)
            n.pop()

    rec(0, Atgt, Ktgt, 0, 0, [])
    return best


