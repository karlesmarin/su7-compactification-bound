def hnf_index(rows, dim):
    """index of the sublattice of Z^dim generated by `rows` (0 if not full rank)."""
    M = [list(r[:dim]) for r in rows]
    piv, idx = 0, 1
    for c in range(dim):
        # find a row at or below `piv` with a nonzero entry in column c
        r = next((i for i in range(piv, len(M)) if M[i][c]), None)
        if r is None:
            return 0
        M[piv], M[r] = M[r], M[piv]
        # gcd-reduce column c below the pivot
        for i in range(piv + 1, len(M)):
            while M[i][c]:
                f = M[piv][c] // M[i][c]
                M[piv] = [a - f * b for a, b in zip(M[piv], M[i])]
                M[piv], M[i] = M[i], M[piv]
        idx *= abs(M[piv][c])
        piv += 1
    return idx


